#!/usr/bin/env node
//=============================================================================
// PokéMZ - tools/build-showdown.js
//=============================================================================

/**
 * @file Bundles the Pokémon Showdown simulator (@pkmn/sim) into
 *       game/js/plugins/PS_Sim.js as the global PSSim, with an MZ plugin
 *       header. Run with "npm run build:showdown".
 */

"use strict";

const path = require("path");
const esbuild = require("esbuild");

const banner = [
    "/*:",
    " * @target MZ",
    " * @plugindesc Pokémon Showdown simulator (bundled @pkmn/sim). Exposes the global PSSim.",
    " * @author Pokémon Showdown contributors, pkmn (bundled for PokéMZ)",
    " *",
    " * @help",
    " * Generated by tools/build-showdown.js. Do not edit; rebuild instead.",
    " * Required by PokeMZ_PBS_Battle. Place it at the top of the plugin list.",
    " */",
].join("\n");

esbuild
    .build({
        entryPoints: [path.join(__dirname, "showdown", "ps-entry.js")],
        bundle: true,
        minify: true,
        format: "iife",
        globalName: "PSSim",
        platform: "browser",
        target: "chrome85",
        outfile: path.join(__dirname, "..", "game", "js", "plugins", "PS_Sim.js"),
        banner: { js: banner },
        legalComments: "none",
        logLevel: "info",
    })
    .catch(() => process.exit(1));
